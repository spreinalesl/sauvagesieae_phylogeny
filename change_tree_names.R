###########################################
## This script read trees and change 
## sample names
###########################################

## Packages
library(ape)

## Input paths
fnamespath <- ""
namesfile <- "sppidTOsppname.csv"
fpath <- paste("~/projects/rbgk/users_area/sreinales/results/sauvagesieae/hybpiper/fasta_files",
                "/", probename, "/", type, "/", sep = "")

## Read data and iterate files
fpattern <- "tre"
ffiles  <- list.files(fpath, pattern = fpattern)

## Iterate files
 for(i in ffiles){

  ## Read tree
  t <- read.tree(paste(fpath, i, sep = ""))
 
  ## Read names table
  smp_names <- read.csv(paste(fnamespath, namesfile, sep = ""), as.is = T)
  
  ## Iterate sample names
  for(n in 1:length(t$tip.label)){
  
    if(grepl(pattern = "\\.", t$tip.label[n])){
      
      ## Change sample names from a ID to spp names file for paralogous seqs
      sname <- strsplit(t$tip.label[n], split = "\\.")
      sname_mod <- smp_names$abbrev[which(smp_names$seqID == sname[[1]][1])]
      t$tip.label[n] <- gsub(pattern = sname[[1]][1], replacement = sname_mod, t$tip.label[n], fixed = T)  
      
    }else{
     
      ## Change sample names from a ID to spp names file for trees generated by iqtree or raxml without
      ## paralogous seqs
      t$tip.label[n] <- smp_names$abbrev[which(smp_names$seqID == t$tip.label[n])]
    }
  }
  
  ## Write modified tree
  write.tree(t, file = paste(fpath, i, sep = ""))
  
  cat("Editing tree", i, "\n")
 }
