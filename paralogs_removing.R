###########################################
## This script check gene trees for genes
## containing paralogous sequences as tagged
## by Hybpiper, in case that paralogs are
## in different clades, they are removed from
## the original fasta matrix
###########################################

## Packages
library(ape)

## Input paths
probe <- "schn"
ppath <- "~/projects/rbgk/users_area/sreinales/results/sauvagesieae/hybpiper/paralogs/"
fpath <- "~/projects/rbgk/users_area/sreinales/results/sauvagesieae/hybpiper/fasta_files/"
aptpth <- paste(ppath, probe, "/trees/", sep = "")
aptl <- paste(ppath, probe, "/paralogs_above_threshold_report.txt", sep = "")
apff <- paste(fpath, probe, "/exons/", sep = "")

# output files
ffnew <- paste(fpath, probe, "/exons/putative_orth/", sep = "")

## Read paralogs_retrieve output from Hybpiper and extract the list of loci with
## paralogous sequences
plist <- readLines(aptl)
p <- grep(pattern = "genes with paralogs", x = plist)
loci_w_p <- plist[(p+1):length(plist)] 

## List trees and fastas
tfiles  <- list.files(aptpth, pattern = "\\.tre")
ffiles <- list.files(apff, pattern = "\\.FNA", full.names = T)
warning_list <- c()
monop <- c()
non_monop <- c()

## Iterate tree files containing all paralogous sequences
for(i in tfiles){
 
  ## Extract locus name
  lnm <- gsub(pattern = "_.+", replacement = "", x = i)
  
  ## Check if this locus was tagged by Hybpiper as having paralogs
  if(!(lnm %in% loci_w_p)){
    warning_list <- rbind(warning_list, lnm)
  } else{
    
    ## Read the gene tree
    t <- read.tree(paste(aptpth, i, sep = ""))
    
    ## Extract the list of paralogous sequences
    # But first, check if only paralog names have point (.)
    pnm <- grep(pattern = "\\.", x = t$tip.label, value = T) 
    tst <- unique(gsub(pattern = "^.+\\.", replacement = "", x = pnm))
    allwdv <- c("main", 0:9)

    if(!unique(tst %in% allwdv)){
      
      stop("Tip labels should not contain points (.)")
      
    } else{
      
      ## List samples with paralogous sequences for the i locus
      locin <- unique(gsub(pattern = "\\..+", replacement = "", x = pnm))
      
      ## Read the fasta file for i retrieved by Hibpiper containing just .main seq
      ff <- grep(pattern = lnm, ffiles, value = T, fixed = T)
      aplgsf <- read.FASTA(file = ff)
      rmp <- c()
      
      ## Iterate each sample with paralogs, check if all sequences form a clade
      for(j in locin){
        ptips <- grep(pattern = j, x = pnm, value = T) 
        mono_test <- is.monophyletic(t, tips = ptips)
        
        if(mono_test){
          ## Keep .main sequence in the fasta file generated by hybpiper
          # if all paralogs form a clade. Write seq names in a log file
          monop <- rbind(monop, paste(lnm, paste0(ptips, collapse = "\t"), sep = "\t"))
        
        } else{
          
          ## if paralogs do not form a clade, remove them for the original fasta file
          rmp <- c(rmp, grep(pattern = j, x = gsub(x = labels(aplgsf), pattern = " .+", replacement = "")))
          
          ## Removed sequences
          non_monop <- rbind(non_monop, paste(lnm, paste0(ptips, collapse = "\t"), sep = "\t"))
        }
      }
      
      ##  If there are paralog sequences to remove
      if(length(rmp) > 0){
        aplgsf <- aplgsf[-rmp]
        
        ## write fasta file without paralogs
        write.FASTA(x = aplgsf, file = gsub(x = ff, pattern = "/exons/", replacement = "/exons/putative_orth/"))
      }
      
      ## Test if .main sequences and other sequences (i.e. x.0, x.1) form the same clades 
      # that is a good idea but its implementation is challenging :/ at least at this moment
    }
  }
  
  cat("Analysing tree", i, "\n")
}

## Print warnings
cat("Those loci were not tagged as containing paralogs by Hybpiper" , warning_list,
    "Those paralogs do not form a clade in the gene tree. Then, the .main sequence retreived by Hybpiper was removed from the fasta file", non_monop,
    "Those paralogs form a clade and the .main sequence was keept in the fasta file", monop, sep = "\n", file = paste(ffnew, "/out.log", sep = ""))
