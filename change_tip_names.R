###########################################
## This script reads trees and changes 
## sample names for species names
###########################################

## Packages
library(ape)

## Input paths
mtype <- "smp30_prlgbothgns_outliers_rm_exons"
program <- "iqtree"
fpath <- "./"

# ID to species names table
fnamespath <- "TableS3_hybpiper_summary.csv" ## This table contains sample IDs and species names

## Output path
ofolder <- "names_ed"
opath <- paste("~/projects/trees", mtype, program, ofolder, sep = "/")

## Read data and iterate files
fpattern <- "gtrees.tre$"
ffiles  <- list.files(fpath, pattern = fpattern)

## Iterate files
for(i in ffiles){

  ## Read names table
  smp_names <- read.csv(fnamespath, as.is = T)
   
  ## Read tree
  to <- read.tree(paste(fpath, i, sep = ""))
 
  ## Test multiphylo
  if(inherits(to, "multiPhylo")){
    tl <- length(to)
  } else{
    tl <- 1
  }
  
  ## Iterate trees if i is multiphylo
  for(mp in 1:tl){
    
    if(tl > 1){
      tr <- to[[mp]]  
    }else{
      tr <- to
    }
    
    ## Iterate sample names
    for(n in 1:length(tr$tip.label)){
      
      if(grepl(pattern = "\\.", tr$tip.label[n])){
        
        ## Change sample names from a ID to spp names file for paralogous seqs
        sname <- strsplit(tr$tip.label[n], split = "\\.")
        sname_mod <- smp_names$abbrev[which(smp_names$seqID == sname[[1]][1])]
        tr$tip.label[n] <- gsub(pattern = sname[[1]][1], replacement = sname_mod, tr$tip.label[n], fixed = T)  
        
      }else{
        
        ## Change sample names from a ID to spp names file for trees generated by iqtree or raxml without
        ## paralogous seqs
        tr$tip.label[n] <- smp_names$abbrev[which(smp_names$seqID == tr$tip.label[n])]
      }
    }
    
    ## Write modified tree
    write.tree(tr, file = paste(opath, "/", i, sep = ""), append = T)
  }
}
